// Generates src/modules/<module>/actions.ts ("use server" public surface) from the
// `export const xxxAction = defineAction(...)` handlers in handlers.ts.
// Run after adding/removing a handler: npm run gen:actions
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = path.join(root, "src", "modules");

for (const mod of fs.readdirSync(modulesDir)) {
  const handlers = path.join(modulesDir, mod, "handlers.ts");
  if (!fs.existsSync(handlers)) continue;
  const names = [...fs.readFileSync(handlers, "utf8").matchAll(/export const (\w+Action) = defineAction/g)].map((m) => m[1]);
  const out = [
    `"use server";`,
    ``,
    `// GENERATED by scripts/gen-actions.mjs. Do not edit by hand.`,
    `// Public server-action surface for the ${mod} module. Each entry delegates to a`,
    `// validated, permission-checked handler in ./handlers.ts. Nothing else is callable from the browser.`,
    ``,
    `import type { ActionState } from "@/core/action";`,
    `import * as h from "./handlers";`,
    ``,
    ...names.map((n) => `export async function ${n}(prev: ActionState, fd: FormData): Promise<ActionState> {\n  return h.${n}(prev, fd);\n}\n`),
  ].join("\n");
  fs.writeFileSync(path.join(modulesDir, mod, "actions.ts"), out);
  console.log(`${mod}: ${names.length} actions`);
}
