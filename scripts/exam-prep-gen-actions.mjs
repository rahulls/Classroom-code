// Generates src/modules/exam-prep/actions.ts ("use server") from the `export const xAction = epAction(`
// handlers in ep-handlers.ts. Run after adding a handler: npm run exam-prep:gen-actions
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/modules/exam-prep");
const names = [...fs.readFileSync(path.join(dir, "ep-handlers.ts"), "utf8").matchAll(/export const (\w+Action) = epAction\(/g)].map((m) => m[1]);
const out = [
  `"use server";`,
  ``,
  `// GENERATED by scripts/exam-prep-gen-actions.mjs. Do not edit by hand.`,
  `// Exam Prep's public server actions. Each forwards to a checked handler in ./ep-handlers.ts.`,
  ``,
  `import type { EpResult } from "./action";`,
  `import * as h from "./ep-handlers";`,
  ``,
  ...names.map((n) => `export async function ${n}(prev: EpResult, fd: FormData): Promise<EpResult> {\n  return h.${n}(prev, fd);\n}\n`),
].join("\n");
fs.writeFileSync(path.join(dir, "actions.ts"), out);
console.log(`exam-prep: ${names.length} actions`);
