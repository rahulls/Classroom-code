// Generates .env with strong random secrets. Never overwrites an existing .env.
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");

if (fs.existsSync(envPath)) {
  console.log(".env already exists; leaving it untouched.");
  process.exit(0);
}

const hex = (n) => randomBytes(n).toString("hex");
const b64 = (n) => randomBytes(n).toString("base64");

const dbUser = "rsc";
const dbName = "rsc_classroom";
const dbPassword = hex(24);
const redisPassword = hex(24);
const setupToken = hex(24);

const env = `# Generated by npm run setup on ${new Date().toISOString()}. Keep this file private.
APP_URL=http://localhost:4310

WEB_PORT=4310
WORKER_PORT=4311
STUDIO_PORT=4312
DB_PORT=54329
REDIS_PORT=63790
SMTP_PORT=10250
MAILPIT_UI_PORT=10251

DB_USER=${dbUser}
DB_NAME=${dbName}
DB_PASSWORD=${dbPassword}
DATABASE_URL=postgresql://${dbUser}:${dbPassword}@127.0.0.1:54329/${dbName}?schema=public

REDIS_PASSWORD=${redisPassword}
REDIS_URL=redis://:${redisPassword}@127.0.0.1:63790

ENCRYPTION_KEY=${b64(32)}
BLIND_INDEX_KEY=${b64(32)}

SETUP_TOKEN=${setupToken}

SESSION_IDLE_HOURS=12
SESSION_ABSOLUTE_DAYS=7
COOKIE_SECURE=false
REQUIRE_2FA=false

# Emails allowed to use Edit mode (modify every record). Must also be the Owner account.
FULL_EDIT_EMAILS=
`;

fs.writeFileSync(envPath, env, { mode: 0o600 });
console.log("Created .env with fresh secrets.");
console.log("\nOne-time SETUP TOKEN (needed at http://localhost:4310/setup):\n  " + setupToken + "\n");
console.log("Back up ENCRYPTION_KEY somewhere safe. Encrypted data can't be recovered without it.");
